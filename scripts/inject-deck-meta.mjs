/**
 * Generate js/deck-meta.js from package.json version + platform-bridge.js BRIDGE_API.
 * Run before dev (prestart) and as part of package:platform.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(__dirname, '..');

export function resolveDeckPackageJson(root = ROOT) {
  if (process.env.DECK_PACKAGE) {
    return path.resolve(process.env.DECK_PACKAGE);
  }
  if (process.env.CONTENT_DIR) {
    const overlay = path.resolve(process.env.CONTENT_DIR, '..', 'package.json');
    if (fs.existsSync(overlay)) {
      return overlay;
    }
  }
  return path.join(root, 'package.json');
}

export function parseBridgeApiFromSource(source) {
  const match = source.match(/BRIDGE_API\s*=\s*(\d+)/);
  if (!match) {
    throw new Error('platform-bridge.js: BRIDGE_API constant not found');
  }
  return Number(match[1]);
}

export function identityFromPackageJson(pkg) {
  const version = pkg.version;
  if (!version) {
    throw new Error('package.json: version field is required');
  }
  const deck_id = pkg.deck?.id;
  if (!deck_id || typeof deck_id !== 'string') {
    throw new Error('package.json: deck.id is required');
  }
  const title = pkg.deck?.title;
  if (!title || typeof title !== 'string') {
    throw new Error('package.json: deck.title is required');
  }
  return { version, deck_id, title, revealVersion: pkg.revealVersion ?? null };
}

export function readDeckMeta() {
  const pkg = JSON.parse(fs.readFileSync(resolveDeckPackageJson(), 'utf8'));
  const identity = identityFromPackageJson(pkg);

  const bridgeSource = fs.readFileSync(path.join(ROOT, 'js/platform-bridge.js'), 'utf8');
  const bridge_api = parseBridgeApiFromSource(bridgeSource);

  return { ...identity, bridge_api };
}

const REQUIRED_BRIDGE_API = 3;

export function buildPlatformManifest(meta, pollScan, boardScan) {
  if (meta.bridge_api < REQUIRED_BRIDGE_API) {
    throw new Error(
      `platform-bridge.js: BRIDGE_API ${meta.bridge_api} is below required ${REQUIRED_BRIDGE_API}`
    );
  }
  const title = meta.title;
  if (!title) {
    throw new Error('package.json: deck.title is required for the platform manifest');
  }
  const manifest = {
    deck_id: meta.deck_id,
    version: meta.version,
    bridge_api: meta.bridge_api,
    title,
    entry_point: 'index.html',
    reveal_version: meta.revealVersion,
    capabilities: ['reveal', 'whiteboard', 'annotations', 'polls', 'crt_fx'],
  };
  if (pollScan.poll_definitions.length > 0) {
    manifest.poll_markers = pollScan.poll_markers;
    manifest.poll_definitions = pollScan.poll_definitions;
  }
  if (boardScan.board_ids.length > 0) {
    manifest.board_ids = boardScan.board_ids;
  }
  return manifest;
}

export function buildDeckMetaJs(meta) {
  const payload = {
    version: meta.version,
    bridge_api: meta.bridge_api,
    deck_id: meta.deck_id,
  };
  if (meta.title) {
    payload.title = meta.title;
  }
  if (meta.poll_definitions?.length) {
    payload.poll_definitions = meta.poll_definitions;
    payload.poll_markers = meta.poll_markers ?? meta.poll_definitions.map((d) => d.poll_id);
    payload.capabilities = meta.capabilities ?? ['reveal', 'whiteboard', 'annotations', 'polls', 'crt_fx'];
  }
  return (
    '/** Generated by scripts/inject-deck-meta.mjs — do not edit. */\n' +
    `window.__DECK_META__ = ${JSON.stringify(payload, null, 2)};\n`
  );
}

export function injectDeckMeta() {
  const meta = readDeckMeta();
  const outPath = path.join(ROOT, 'js/deck-meta.js');
  fs.writeFileSync(outPath, buildDeckMetaJs(meta), 'utf8');
  return meta;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  try {
    const meta = injectDeckMeta();
    console.log(
      `inject-deck-meta: OK (v${meta.version}, bridge_api=${meta.bridge_api}, deck_id=${meta.deck_id})`
    );
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
